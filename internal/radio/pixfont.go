// Кириллица, совпадающая с латиницей по начертанию, берёт латинский глиф.
var sameAs = map[rune]rune{
	'А': 'A', 'В': 'B', 'Е': 'E', 'К': 'K', 'М': 'M', 'Н': 'H', 'О': 'O', 'Р': 'P',
	'С': 'C', 'Т': 'T', 'Х': 'X', 'І': 'I', 'Ү': 'Y', 'Һ': 'H', 'Ј': 'J', 'Ѕ': 'S',
	'Ä': 'A', 'Ö': 'O', 'Ü': 'U', 'É': 'E', 'È': 'E', 'Á': 'A', 'Ó': 'O', 'Í': 'I', 'Ñ': 'N', 'Ç': 'C',
	'“': '"', '”': '"', '„': '"', '‘': '\'', '’': '\'', '•': '·', '×': 'X', '♫': '♪',
}

func glyph(r rune) ([7]string, bool) {
	r = unicode.ToUpper(r)
	if g, ok := glyphs[r]; ok {
		return g, true
	}
	if s, ok := sameAs[r]; ok {
		return glyphs[s], true
	}
	return glyphs['?'], false
}

// wrapText режет строку на строки не длиннее width символов — по словам, а слишком длинное
// слово по символам; больше maxLines — последняя строка кончается многоточием.
func wrapText(s string, width, maxLines int) []string {
	var lines []string
	var cur []rune
	flush := func() { lines = append(lines, strings.TrimSpace(string(cur))); cur = cur[:0] }
	for _, word := range strings.Fields(s) {
		w := []rune(word)
		for len(w) > 0 {
			sp := 0
			if len(cur) > 0 {
				sp = 1
			}
			if len(cur)+sp+len(w) <= width {
				if sp == 1 {
					cur = append(cur, ' ')
				}
				cur = append(cur, w...)
				w = nil
			} else if len(cur) == 0 { // слово длиннее строки
				cur = append(cur, w[:width]...)
				w = w[width:]
				flush()
			} else {
				flush()
			}
		}
	}
	if len(cur) > 0 {
		flush()
	}
	if len(lines) > maxLines {
		last := []rune(lines[maxLines-1])
		if len(last) > width-1 {
			last = last[:width-1]
		}
		lines = append(lines[:maxLines-1], strings.TrimSpace(string(last))+"…")
	}
	return lines
}
